import numpy as np
import logging
from typing import Dict, List, Any
from app.config import (
    FRAUD_THRESHOLD_LOW,
    FRAUD_THRESHOLD_HIGH,
    PINNED_HF_REPO,
    PINNED_HF_REVISION,
    MODEL_FILENAME,
)
from app.model.model_loader import load_fraud_model
from app.schemas.fraud import FraudScoreRequest, FraudScoreResponse
from app.services.benchmark_fixtures import BENCHMARK_FIXTURES, get_fixture_vector

logger = logging.getLogger("crossbridge.fraud_service")

def score_fraud(request: FraudScoreRequest) -> FraudScoreResponse:
    model, feature_names = load_fraud_model()

    # Determine input vector
    values: List[float] = []

    if request.benchmark_fixture_key:
        values = get_fixture_vector(request.benchmark_fixture_key, request.transfer_amount)
    elif request.feature_vector is not None:
        if len(request.feature_vector) != 29:
            raise ValueError(f"feature_vector must contain exactly 29 elements, received {len(request.feature_vector)}")
        values = [float(x) for x in request.feature_vector]
        if request.transfer_amount is not None:
            values[-1] = float(request.transfer_amount)
    elif request.features is not None:
        # Check all 29 features exist in features dict
        missing = [f for f in feature_names if f not in request.features]
        if missing:
            raise ValueError(f"Missing required PCA/Amount features in request: {missing[:5]} (total missing: {len(missing)})")
        values = [float(request.features[f]) for f in feature_names]
        if request.transfer_amount is not None:
            values[-1] = float(request.transfer_amount)
    else:
        # Default to standard clean benchmark fixture if no features provided
        values = get_fixture_vector("LEGIT_CLEAN", request.transfer_amount)

    X = np.array(values, dtype=np.float64).reshape(1, -1)

    # Perform inference with LightGBM
    probas = model.predict_proba(X)[0]
    legit_prob = float(probas[0])
    fraud_prob = float(probas[1])

    # Determine prediction class and decision
    if fraud_prob >= FRAUD_THRESHOLD_HIGH:
        decision = "REJECT"
        risk_level = "HIGH"
        pred_class = 1
    elif fraud_prob >= FRAUD_THRESHOLD_LOW:
        decision = "MANUAL_REVIEW"
        risk_level = "MEDIUM"
        pred_class = 1 if fraud_prob >= 0.5 else 0
    else:
        decision = "APPROVE"
        risk_level = "LOW"
        pred_class = 0

    # Calculate feature anomaly magnitude
    top_features: List[Dict[str, Any]] = []
    for name, val in zip(feature_names, values):
        if name != "Amount":
            # For PCA features, deviations > 1.5 standard deviations are significant
            deviation = abs(val)
            if deviation > 1.2:
                top_features.append({
                    "feature": name,
                    "value": round(val, 3),
                    "significance": "HIGH" if deviation > 3.0 else "MODERATE",
                    "direction": "NEGATIVE" if val < 0 else "POSITIVE"
                })
    # Sort by deviation descending
    top_features.sort(key=lambda item: abs(item["value"]), reverse=True)
    top_features = top_features[:5]

    return FraudScoreResponse(
        fraud_probability=round(fraud_prob, 5),
        legitimate_probability=round(legit_prob, 5),
        prediction=pred_class,
        decision=decision,
        risk_level=risk_level,
        thresholds_applied={
            "low_threshold": FRAUD_THRESHOLD_LOW,
            "high_threshold": FRAUD_THRESHOLD_HIGH,
            "binary_cutoff": 0.50
        },
        top_contributing_features=top_features,
        model_provenance={
            "huggingface_repo": PINNED_HF_REPO,
            "pinned_revision": PINNED_HF_REVISION,
            "artifact_file": MODEL_FILENAME,
            "training_dataset": "ULB credit card fraud benchmark (creditcard.csv, 28 col PCA + Amount)"
        },
        prototype_disclosure=(
            "PROTOTYPE BENCHMARK NOTICE: This score is generated by a LightGBM classifier trained on the "
            "ULB credit card fraud benchmark dataset (V1-V28 PCA features and Amount). It demonstrates machine "
            "learning scoring over tabular latent embeddings for the hackathon prototype. It does NOT constitute "
            "a calibrated production prediction of interbank wire fraud or real-world money laundering."
        )
    )
